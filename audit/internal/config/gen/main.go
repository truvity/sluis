// Command gen writes the configuration schemas of version 2 into schemas/config/, and the
// chart's values schema, which embeds them, into charts/audit/. Run it
// through `just config-schemas`; the drift check fails when the committed files
// are not what it writes.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/truvity/sluis/audit/internal/config/schema"
	"github.com/truvity/sluis/audit/profile"
)

func main() {
	dir := "schemas/config"
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fail(err)
	}
	chart := "../charts/audit/values.schema.json"
	if len(os.Args) > 2 {
		chart = os.Args[2]
	}
	if err := os.WriteFile(chart, schema.Values(), 0o644); err != nil {
		fail(err)
	}
	presets := "../charts/audit/templates/_presets.tpl"
	if len(os.Args) > 3 {
		presets = os.Args[3]
	}
	if err := os.WriteFile(presets, presetTable(), 0o644); err != nil {
		fail(err)
	}
	for _, name := range append(append([]string{}, schema.Names...), schema.Documents...) {
		body, _ := schema.Schema(name)
		if err := os.WriteFile(filepath.Join(dir, name+".schema.json"), body, 0o644); err != nil {
			fail(err)
		}
	}
}

// presetTable is the chart's copy of what each framework profile says its
// lowest install preset is (min_preset in profiles/<name>.yaml). A chart cannot
// read the profile files, so the table is written from them here and the drift
// check holds the committed file to it; the chart derives the preset from it with
// the same rule as profile.Deployment.Derive.
func presetTable() []byte {
	fw, err := profile.Builtin()
	if err != nil {
		fail(err)
	}
	names := make([]string, 0, len(fw))
	for name := range fw {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("{{- /* Code generated by `just audit-config-schemas` from audit/profiles/*.yaml (min_preset). DO NOT EDIT. */ -}}\n")
	b.WriteString("{{- define \"audit.frameworkPresets\" -}}\n")
	for _, name := range names {
		fmt.Fprintf(&b, "%s: %s\n", name, fw[name].MinPreset)
	}
	b.WriteString("{{- end -}}\n")
	return []byte(b.String())
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "config-schemas:", err)
	os.Exit(1)
}
