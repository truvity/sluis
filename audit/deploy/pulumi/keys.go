var addressRE = regexp.MustCompile(`^internal(/[A-Za-z0-9_][A-Za-z0-9_.-]*)+$`)

// checkStateRoot holds a state root to what Writer.Secrets.Root is held to.
func checkStateRoot(root, name string) error {
	if !rootRE.MatchString(root) || !strings.HasPrefix(root, "/audit/") {
		return fmt.Errorf("auditpulumi: State.Root %q must be an SSM parameter path under /audit/ such as /audit/%s: "+
			"at least two segments, the first `audit`, segments of letters, digits, . _ and -, no trailing slash, no wildcard", root, name)
	}
	for _, seg := range strings.Split(root[1:], "/") {
		if seg == "." || seg == ".." || strings.HasPrefix(seg, ".") {
			return fmt.Errorf("auditpulumi: State.Root %q has the segment %q: no segment may start with a dot", root, seg)
		}
	}
	return nil
}

// stateGrant is what a role is given of the installation's state store: read
// some parameters, read and create others.
type stateGrant struct {
	Region, Account, KeyArn string
	// Read are parameter paths read; Write are path prefixes (with /*) read and
	// created.
	Read, Write []string
}

func (g *stateGrant) arn(path string) string {
	return "arn:" + "aws:ssm:" + g.Region + ":" + g.Account + ":parameter" + path
}

func (g *stateGrant) statements() []statement {
	if g == nil || (len(g.Read) == 0 && len(g.Write) == 0) {
		return nil
	}
	var st []statement
	if len(g.Read) > 0 {
		arns := make([]string, len(g.Read))
		for i, p := range g.Read {
			arns[i] = g.arn(p)
		}
		st = append(st, allow([]string{"ssm:GetParameter"}, arns, nil))
	}
	if len(g.Write) > 0 {
		arns := make([]string, len(g.Write))
		for i, p := range g.Write {
			arns[i] = g.arn(p)
		}
		// PutParameter without overwrite creates a parameter and fails on an
		// existing one, which is what the state store's PutIfAbsent relies on; the
		// role is not granted a way to replace or delete one.
		st = append(st, allow([]string{"ssm:GetParameter", "ssm:PutParameter"}, arns, nil))
	}
	if g.KeyArn != "" {
		actions := []string{"kms:Decrypt"}
		if len(g.Write) > 0 {
			actions = append(actions, "kms:GenerateDataKey", "kms:Encrypt")
		}
		st = append(st, allow(actions, []string{g.KeyArn}, map[string]any{
			"StringEquals": map[string]any{"kms:ViaService": "ssm." + g.Region + ".amazonaws.com"},
		}))
	}
	return st
}

// checkEndpoint holds an endpoint to an https URL with a host and no path.
func checkEndpoint(field, endpoint string) error {
	u, err := url.Parse(endpoint)
	if err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil || (u.Path != "" && u.Path != "/") || u.RawQuery != "" {
		return fmt.Errorf("auditpulumi: %s %q must be an https URL with a host and no path or credentials: "+
			"the credentials are kept in the state store, and a request to the store crosses this URL", field, endpoint)
	}
	return nil
}
