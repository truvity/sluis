package releasecheck

import (
	"bufio"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"go.yaml.in/yaml/v3"
)

// TestTheModuleImagesAreOnePerModuleEachPinnedToItsModule holds the module
// images to hack/release-zips.txt and hack/release-images.txt (the list the
// release workflow's attest-oci matrix and release-verify read), and writes the
// result as a golden: an image added, renamed or unpinned is a reviewed change,
// and none can be published without a signature.
//
// The images are built by hack/module-images.sh from hack/ko-modules/.ko.yaml
// and NOT by goreleaser's `kos`: goreleaser pushes every ko entry to
// $KO_DOCKER_REPO whatever its own repository says, so three entries built from
// ./cmd/sluis landed on one name (v1.75.0-rc.5). `just release-lint` pushes them
// to a throwaway registry and asserts the names; this test holds the config.
func TestTheModuleImagesAreOnePerModuleEachPinnedToItsModule(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join(root, ".goreleaser.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	var cfg struct {
		Kos []struct {
			ID        string   `yaml:"id"`
			Build     string   `yaml:"build"`
			Ldflags   []string `yaml:"ldflags"`
			Platforms []string `yaml:"platforms"`
			BaseImage string   `yaml:"base_image"`
			SBOM      string   `yaml:"sbom"`
		} `yaml:"kos"`
	}
	if err = yaml.Unmarshal(raw, &cfg); err != nil {
		t.Fatal(err)
	}
	// The module images are not goreleaser's: a kos entry for one would push to
	// the shared $KO_DOCKER_REPO and collide with the others.
	var golden strings.Builder
	golden.WriteString("# image | module pin | platforms | base (generated by TestTheModuleImagesAreOnePerModuleEachPinnedToItsModule;" +
		" UPDATE_GOLDEN=1 rewrites)\n")
	for _, k := range cfg.Kos {
		if strings.HasPrefix(k.ID, "sluis-") {
			t.Errorf("kos entry %s: a module image built by goreleaser is pushed to $KO_DOCKER_REPO, not to its own name; add it to hack/ko-modules/.ko.yaml", k.ID)
			continue
		}
		if k.BaseImage != "gcr.io/distroless/static:nonroot" || k.SBOM != "none" || strings.Join(k.Platforms, ",") != "linux/amd64,linux/arm64" {
			t.Errorf("image %s: base %q sbom %q platforms %v differ from the module images'", k.ID, k.BaseImage, k.SBOM, k.Platforms)
		}
		if k.ID == "sluis" {
			if k.Build != "sluis" {
				t.Errorf("the sluis image is the unpinned multi-call build, got build %q", k.Build)
			}
			golden.WriteString("ghcr.io/truvity/sluis/sluis |  | " + strings.Join(k.Platforms, ",") + " | " + k.BaseImage + "\n")
		}
	}

	// hack/ko-modules/.ko.yaml: the one build every module image shares.
	koRaw, err := os.ReadFile(filepath.Join(root, "hack", "ko-modules", ".ko.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	var ko struct {
		BaseImage string   `yaml:"defaultBaseImage"`
		Platforms []string `yaml:"defaultPlatforms"`
		Builds    []struct {
			Main    string   `yaml:"main"`
			Ldflags []string `yaml:"ldflags"`
		} `yaml:"builds"`
	}
	if err = yaml.Unmarshal(koRaw, &ko); err != nil {
		t.Fatal(err)
	}
	if len(ko.Builds) != 1 || ko.Builds[0].Main != "./cmd/sluis" {
		t.Fatalf("hack/ko-modules/.ko.yaml: want one build of ./cmd/sluis (the k8s main; the cmd/sluis-<module> mains are Lambda-only), got %+v", ko.Builds)
	}
	if ko.BaseImage != "gcr.io/distroless/static:nonroot" || strings.Join(ko.Platforms, ",") != "linux/amd64,linux/arm64" {
		t.Errorf("hack/ko-modules/.ko.yaml: base %q platforms %v differ from the sluis image's", ko.BaseImage, ko.Platforms)
	}
	pinned := false
	for _, l := range ko.Builds[0].Ldflags {
		if strings.Contains(l, "internal/version.Module=sluis-module={{ .Env.SLUIS_MODULE }}") {
			pinned = true
		}
	}
	if !pinned {
		t.Errorf("hack/ko-modules/.ko.yaml does not pin the module with -X .../version.Module=sluis-module={{ .Env.SLUIS_MODULE }}: an image would run as another module")
	}

	// hack/release-images.txt: the images it lists. hack/module-images.sh builds
	// exactly its sluis-* lines, so the list is the set.
	f, err := os.Open(filepath.Join(root, "hack", "release-images.txt"))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	modules := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) == 2 && fields[0] == "image" && strings.HasPrefix(fields[1], "ghcr.io/truvity/sluis/sluis-") {
			name := strings.TrimPrefix(fields[1], "ghcr.io/truvity/sluis/sluis-")
			modules[name] = true
			golden.WriteString(fields[1] + " | sluis-module=" + name + " | " + strings.Join(ko.Platforms, ",") + " | " + ko.BaseImage + "\n")
		}
	}
	// Every module with a zip has an image, and no image is for a module without one.
	for _, z := range releaseZips(t) {
		if z.kind == "module" && !modules[z.name] {
			t.Errorf("module %s has a Lambda zip and no container image", z.name)
		}
		delete(modules, z.name)
	}
	for m := range modules {
		t.Errorf("image sluis-%s is for a module with no entry in hack/release-zips.txt", m)
	}
	path := filepath.Join("testdata", "module-images.golden")
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err = os.WriteFile(path, []byte(golden.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != golden.String() {
		t.Errorf("the images changed; review and run UPDATE_GOLDEN=1 go test ./internal/releasecheck\n"+
			"--- golden\n%s--- built from .goreleaser.yaml\n%s", want, golden.String())
	}
}
