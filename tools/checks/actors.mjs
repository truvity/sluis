#!/usr/bin/env node
// The actor registry, docs/architecture/actors.yaml, against everything else that names an actor.
//
//   - the registry itself: one row per actor, closed fields, known groups, languages, rules,
//     placements, key operations, ADR numbers, requirement areas, standards, and the label
//     `actor:<name>`;
//   - the explorer, site/src/data/explorer/architecture.yaml: every role it draws is a registry
//     actor and every core, quota and audit actor is drawn; for a drawn actor the executable, the
//     ports and the calls live in the explorer only, and an actor that is not drawn states them in
//     the registry; the node agent, key-holder and the integration kinds agree;
//   - the ADRs: each ADR an actor lists names it; ADR 0003's table of core actors equals the
//     registry's core group and ADR 0003 names every actor; every instance name `<name>@<...>` in
//     an ADR is an actor, an example integration instance or a declared non-actor; the language
//     and rule of each actor agree with the per-actor table of ADR 0014;
//   - the requirement records: every name in a record's optional `actors:` is an actor, and the
//     record's area is one of that actor's requirement areas;
//   - the generated tables on docs/reference/actors.md are current (`--write` rewrites them).
//
// Needs the `yaml` package of site/ (`just site-install`).
//
// usage: tools/checks/actors.mjs [--write] [repo-root]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { reporter, repoRoot } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const { parse } = createRequire(join(here, '..', '..', 'site', 'package.json'))('yaml');

const root = repoRoot();
const write = process.argv.includes('--write');
const { error, finish } = reporter('check-actors');

const REGISTRY = 'docs/architecture/actors.yaml';
const EXPLORER = 'site/src/data/explorer/architecture.yaml';
const PAGE = 'docs/reference/actors.md';
const BEGIN = '<!-- BEGIN GENERATED by tools/checks/actors.mjs from docs/architecture/actors.yaml; do not edit -->';
const END = '<!-- END GENERATED -->';

const GROUPS = ['core', 'quota', 'audit', 'platform', 'integration'];
const DRAWN_GROUPS = ['core', 'quota', 'audit'];
const LANGUAGES = ['Go', 'Rust'];
const SCOPES = ['per-boundary', 'front', 'per-node', 'per-tenant', 'beside-sluis'];
const INSTANCES = ['any', 'exactly-1'];
const RUNTIMES = ['bare-metal', 'serverless', 'kubernetes'];
const OPS = ['sign', 'public-key', 'wrap', 'unwrap'];
// The ports of ADR 0002.
const PORTS = ['keys', 'state', 'lease', 'blob', 'transport', 'index', 'cloud', 'witness', 'secrets', 'export'];
const FIELDS = ['name', 'group', 'purpose', 'aka', 'contract', 'language', 'language_rule', 'language_row', 'language_note',
  'placement', 'keys', 'binary', 'ports', 'calls', 'adrs', 'requirement_areas', 'standards', 'label', 'issues'];
const REQUIRED = ['name', 'group', 'purpose', 'language', 'language_rule', 'placement', 'keys', 'adrs', 'requirement_areas',
  'standards', 'label', 'issues'];

const read = (rel) => readFileSync(join(root, rel), 'utf8');
const load = (rel) => {
  if (!existsSync(join(root, rel))) return null;
  try { return parse(read(rel)); } catch (e) { error(`${rel}: not valid YAML: ${e.message}`); return null; }
};
const isStrList = (v) => Array.isArray(v) && v.every((x) => typeof x === 'string');
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// ---- the registry
const reg = load(REGISTRY);
if (!reg) {
  error(`${REGISTRY} is missing`);
  finish(0, 'actors');
}
const actors = Array.isArray(reg.actors) ? reg.actors : [];
if (reg.schema !== 1) error(`${REGISTRY}: schema must be 1`);
const byName = new Map();
for (const [i, a] of actors.entries()) {
  const at = `${REGISTRY}: actors[${i}]${a?.name ? ` (${a.name})` : ''}`;
  if (!a || typeof a !== 'object') { error(`${at}: not an object`); continue; }
  for (const k of Object.keys(a)) if (!FIELDS.includes(k)) error(`${at}: unknown field ${k}`);
  for (const k of REQUIRED) if (!(k in a)) error(`${at}: missing ${k}`);
  if (typeof a.name !== 'string' || !/^[a-z][a-z0-9-]*$/.test(a.name)) { error(`${at}: name must be lower-case kebab-case`); continue; }
  if (byName.has(a.name)) error(`${at}: the name is used twice`);
  byName.set(a.name, a);
  if (!GROUPS.includes(a.group)) error(`${at}: group must be one of ${GROUPS.join(', ')}`);
  if (typeof a.purpose !== 'string' || !/^[A-Z"`].{10,300}\.$/.test(a.purpose)) error(`${at}: purpose must be one sentence ending in a period`);
  if (!LANGUAGES.includes(a.language)) error(`${at}: language must be one of ${LANGUAGES.join(', ')}`);
  if (typeof a.language_rule !== 'string' || !/^R(?:[1-9]|1[01])$/.test(a.language_rule)) error(`${at}: language_rule must be R1 to R11 (ADR 0014)`);
  if ('aka' in a && !isStrList(a.aka)) error(`${at}: aka must be a list of strings`);
  if (a.group === 'integration' && typeof a.contract !== 'string') error(`${at}: an integration kind names its contract`);
  if (a.group !== 'integration' && 'contract' in a) error(`${at}: only an integration kind has a contract`);
  const p = a.placement ?? {};
  if (!SCOPES.includes(p.scope)) error(`${at}: placement.scope must be one of ${SCOPES.join(', ')}`);
  if (!INSTANCES.includes(p.instances)) error(`${at}: placement.instances must be one of ${INSTANCES.join(', ')}`);
  if (!isStrList(p.runtimes) || !p.runtimes.length || p.runtimes.some((r) => !RUNTIMES.includes(r))) error(`${at}: placement.runtimes must list runtimes of ${RUNTIMES.join(', ')}`);
  for (const k of Object.keys(p)) if (!['scope', 'instances', 'runtimes', 'note'].includes(k)) error(`${at}: unknown placement field ${k}`);
  if (!Array.isArray(a.keys)) error(`${at}: keys must be a list`);
  for (const [j, k] of (Array.isArray(a.keys) ? a.keys : []).entries()) {
    if (typeof k?.purpose !== 'string' || typeof k?.slot !== 'string') error(`${at}: keys[${j}] needs a purpose and a slot (a string)`);
    if (!isStrList(k?.ops) || !k.ops.length || k.ops.some((o) => !OPS.includes(o))) error(`${at}: keys[${j}].ops must list ${OPS.join(', ')}`);
    for (const f of Object.keys(k ?? {})) if (!['purpose', 'slot', 'ops', 'context'].includes(f)) error(`${at}: keys[${j}]: unknown field ${f}`);
  }
  if (!isStrList(a.adrs) || a.adrs.some((n) => !/^[0-9]{4}$/.test(n))) error(`${at}: adrs must list four-digit record numbers, quoted`);
  if (!isStrList(a.requirement_areas)) error(`${at}: requirement_areas must be a list of area codes`);
  if (!isStrList(a.standards)) error(`${at}: standards must be a list of ids`);
  if (a.label !== `actor:${a.name}`) error(`${at}: label must be actor:${a.name}`);
  if (!Array.isArray(a.issues) || a.issues.some((n) => !Number.isInteger(n) || n < 1) || new Set(a.issues).size !== a.issues.length) error(`${at}: issues must be unique issue numbers`);
}
const instances = reg.integration_instances ?? {};
for (const [vendor, kinds] of Object.entries(instances)) {
  if (!isStrList(kinds) || kinds.some((k) => byName.get(k)?.group !== 'integration')) error(`${REGISTRY}: integration_instances.${vendor} must list integration kinds of the registry`);
}
const notActors = reg.not_actors ?? {};
for (const n of Object.keys(notActors)) if (byName.has(n)) error(`${REGISTRY}: ${n} is both an actor and in not_actors`);

// ---- the requirements vocabulary
const index = load('docs/requirements/index.yaml');
const areas = index?.catalogue?.areas ?? {};
const standardsFile = load('docs/requirements/standards.yaml');
const standards = new Map((standardsFile?.standards ?? []).map((s) => [s.id, s]));
for (const a of actors) {
  for (const c of a.requirement_areas ?? []) if (!(c in areas)) error(`${REGISTRY}: ${a.name}: requirement area ${c} is not declared in docs/requirements/index.yaml`);
  for (const s of a.standards ?? []) if (!standards.has(s)) error(`${REGISTRY}: ${a.name}: standard ${s} is not in docs/requirements/standards.yaml`);
}

// ---- the explorer
const arch = load(EXPLORER);
if (!arch) error(`${EXPLORER} is missing`);
const roles = arch?.roles ?? {};
const drawn = (a) => Object.hasOwn(roles, a.name);
for (const r of Object.keys(roles)) if (!byName.has(r)) error(`${EXPLORER}: role ${r} is not an actor of the registry`);
for (const a of actors) {
  if (drawn(a)) {
    for (const k of ['binary', 'ports', 'calls']) if (k in a) error(`${REGISTRY}: ${a.name}: ${k} is drawn in ${EXPLORER}; state it there only`);
    if (roles[a.name].binary !== `actors/${a.name}`) error(`${EXPLORER}: role ${a.name}: binary must be actors/${a.name}`);
  } else {
    if (DRAWN_GROUPS.includes(a.group)) error(`${REGISTRY}: ${a.name}: a ${a.group} actor must be drawn as a role in ${EXPLORER}`);
    if (typeof a.binary !== 'string') error(`${REGISTRY}: ${a.name}: not drawn in the explorer, so it states its binary`);
    if (!isStrList(a.ports) || a.ports.some((p) => !PORTS.includes(p))) error(`${REGISTRY}: ${a.name}: not drawn in the explorer, so it lists its ports (of ${PORTS.join(', ')})`);
    if (!isStrList(a.calls) || a.calls.some((c) => !byName.has(c))) error(`${REGISTRY}: ${a.name}: not drawn in the explorer, so it lists the actors it calls`);
  }
}
if (arch) {
  const node = byName.get('sluis-node');
  if (!node) error(`${REGISTRY}: the node agent sluis-node is missing`);
  else if (arch.node_agent?.title !== 'sluis-node' || arch.node_agent?.binary !== node.binary) error(`${EXPLORER}: node_agent must be sluis-node with the binary ${node.binary}`);
  const holders = new Set(Object.values(arch.drivers ?? {}).map((d) => d.shared_name).filter(Boolean));
  for (const h of holders) if (!byName.has(h)) error(`${EXPLORER}: the shared driver ${h} is not an actor of the registry`);
  if (!holders.has('key-holder')) error(`${EXPLORER}: no keys driver names key-holder as its shared driver`);
  const kinds = new Set(Object.values(arch.integrations ?? {}).map((i) => i.kind));
  const contracts = new Map(actors.filter((a) => a.group === 'integration').map((a) => [a.contract, a.name]));
  for (const k of kinds) if (!contracts.has(k) && !Object.hasOwn(notActors, k)) error(`${EXPLORER}: integration kind ${k} is neither an integration actor's contract nor in not_actors`);
  for (const [c, n] of contracts) if (!kinds.has(c)) error(`${REGISTRY}: ${n}: contract ${c} is not an integration kind of ${EXPLORER}`);
}

// ---- the ADRs
const adrDir = join(root, 'docs', 'decisions');
const adrFiles = existsSync(adrDir) ? readdirSync(adrDir).filter((f) => /^[0-9]{4}-.*\.md$/.test(f) && !f.startsWith('0000')) : [];
const adr = new Map(adrFiles.map((f) => [f.slice(0, 4), { file: f, slug: f.replace(/\.md$/, ''), text: readFileSync(join(adrDir, f), 'utf8') }]));
// An ADR names an actor by its name in backticks, as an instance `name@...`, or by an aka phrase;
// audit and integration actors and quota are also named in plain prose.
const prose = (a) => ['audit', 'integration', 'quota'].includes(a.group);
function names(text, a) {
  if (text.includes(`\`${a.name}\``) || text.includes(`\`${a.name}@`)) return true;
  const words = [...(a.aka ?? []), ...(prose(a) ? [a.name, a.contract].filter(Boolean) : [])];
  return words.some((w) => new RegExp(`(?<![\\w-])${esc(w)}(?![\\w-])`, 'i').test(text));
}
for (const a of actors) {
  for (const n of a.adrs ?? []) {
    if (!adr.has(n)) error(`${REGISTRY}: ${a.name}: ADR ${n} is not a record in docs/decisions/`);
    else if (!names(adr.get(n).text, a)) error(`${REGISTRY}: ${a.name}: ADR ${n} does not name the actor`);
  }
}
const a0003 = adr.get('0003')?.text;
if (!a0003) error('docs/decisions/: ADR 0003, the actors, is missing');
else {
  const section = /### The actors\n([\s\S]*?)\n### /.exec(a0003)?.[1] ?? '';
  const core = [...section.matchAll(/^\s*\| `([a-z][a-z0-9-]*)` \|/gm)].map((m) => m[1]);
  if (!core.length) error('ADR 0003: no table of core actors under "### The actors"');
  for (const n of core) if (byName.get(n)?.group !== 'core') error(`ADR 0003 names ${n} as a core actor; the registry ${byName.has(n) ? `has it in group ${byName.get(n).group}` : 'lacks it'}`);
  for (const a of actors) {
    if (a.group === 'core' && !core.includes(a.name)) error(`${REGISTRY}: ${a.name} is a core actor that the ADR 0003 table does not list`);
    if (!names(a0003, a)) error(`${REGISTRY}: ${a.name}: ADR 0003 does not name it`);
  }
}
for (const [n, { text }] of adr) {
  for (const m of text.matchAll(/`([a-z][a-z0-9-]*)@[^`\s]+`/g)) {
    const name = m[1];
    if (name.startsWith('sluis-')) continue; // a unit or a service name, such as sluis-ca@prod.service
    if (!byName.has(name) && !Object.hasOwn(instances, name) && !Object.hasOwn(notActors, name)) {
      error(`ADR ${n}: the instance name \`${m[0].slice(1, -1)}\` names ${name}, which is not an actor, an example integration instance or a declared non-actor of ${REGISTRY}`);
    }
  }
}
const a0014 = adr.get('0014')?.text;
if (!a0014) error('docs/decisions/: ADR 0014, the languages, is missing');
else {
  const table = /### Per-actor table\n([\s\S]*?)\n\n(?!\|)/.exec(a0014)?.[1] ?? '';
  const rows = table.split('\n').filter((l) => /^\|/.test(l) && !/^\|[-| ]+\|$/.test(l)).slice(1)
    .map((l) => l.slice(1, -1).split(' | ').map((c) => c.trim()));
  if (!rows.length) error('ADR 0014: no rows under "### Per-actor table"');
  for (const a of actors) {
    const key = a.language_row ?? `\`${a.name}\``;
    const hit = rows.filter((r) => (a.language_row ? r[0] === key : r[0].includes(key)));
    if (hit.length !== 1) { error(`ADR 0014: ${hit.length} rows of the per-actor table name ${key}, expected 1`); continue; }
    const [, lang = '', rule = ''] = hit[0];
    if (!new RegExp(`\\b${a.language}\\b`).test(lang)) error(`${REGISTRY}: ${a.name}: language ${a.language}, but ADR 0014 says "${lang}"`);
    if (!new RegExp(`\\b${a.language_rule}\\b`).test(rule)) error(`${REGISTRY}: ${a.name}: rule ${a.language_rule}, but ADR 0014 gives "${rule}"`);
  }
}

// ---- the requirement records
let annotated = 0;
for (const { file, code } of Object.entries(areas).map(([code, v]) => ({ code, file: v.file }))) {
  const doc = load(`docs/requirements/${file}`);
  for (const r of doc?.requirements ?? []) {
    if (!('actors' in r)) continue;
    annotated++;
    if (!isStrList(r.actors) || !r.actors.length) { error(`docs/requirements/${file}: ${r.id}: actors must be a list of actor names`); continue; }
    for (const n of r.actors) {
      const a = byName.get(n);
      if (!a) error(`docs/requirements/${file}: ${r.id}: ${n} is not an actor of ${REGISTRY}`);
      else if (!(a.requirement_areas ?? []).includes(code)) error(`docs/requirements/${file}: ${r.id}: area ${code} is not a requirement area of ${n} in ${REGISTRY}`);
    }
  }
}

// ---- the generated page
const exUses = (a) => (drawn(a) ? roles[a.name].uses ?? [] : a.ports ?? []);
const intByExplorerId = Object.fromEntries(Object.entries(arch?.integrations ?? {}).map(([id, i]) => [id, actors.find((x) => x.contract === i.kind)?.name]));
function exCalls(a) {
  if (!drawn(a)) return a.calls ?? [];
  const out = [];
  for (const c of arch.calls ?? []) {
    if (c.f !== a.name) continue;
    const t = byName.has(c.t) ? c.t : intByExplorerId[c.t];
    if (t && !out.includes(t)) out.push(t);
  }
  return out;
}
const local = arch?.shapes?.find((s) => s.id === 'local')?.ports ?? {};
const code = (s) => `\`${s}\``;
const list = (xs, none = 'none', sep = ', ') => (xs.length ? xs.join(sep) : none);
const scopeText = { 'per-boundary': 'one per boundary', front: 'in the front installation', 'per-node': 'one per node', 'per-tenant': 'one per vendor tenant and credential', 'beside-sluis': 'beside sluis, or on its own' };
const keyText = (k) => `${code(k.purpose)}, slot ${k.slot === 'spare' ? 'from the spare range' : k.slot === 'none' ? 'none (not a card key)' : k.slot === 'open' ? 'not yet assigned ([open](#open-items))' : code(k.slot)}: ${k.ops.join(', ')}${k.context ? `; ${k.context}` : ''}`;
const adrLink = (n) => (adr.has(n) ? `[ADR ${n}](/decisions/${adr.get(n).slug}/)` : `ADR ${n}`);
const issueLink = (n) => `[#${n}](https://github.com/truvity/sluis/issues/${n})`;

function render() {
  const out = [BEGIN, ''];
  out.push('| Actor | Group | Language | Runs | Label |', '|---|---|---|---|---|');
  for (const a of actors) {
    out.push(`| [${code(a.name)}](#${a.name}) | ${a.group} | ${a.language} (${a.language_rule}) | ${scopeText[a.placement.scope]}${a.placement.instances === 'exactly-1' ? ', exactly 1' : ''} | ${code(a.label)} |`);
  }
  for (const a of actors) {
    const ports = exUses(a);
    const drivers = ports.filter((p) => local[p]).map((p) => `${p}: ${code(local[p])}`);
    out.push('', `### ${code(a.name)}`, '', a.purpose, '');
    out.push(`- **Language:** ${a.language}, rule ${a.language_rule} of ${adrLink('0014')}.${a.language_note ? ` ${a.language_note}` : ''}`);
    out.push(`- **Placement:** ${scopeText[a.placement.scope]}; ${a.placement.instances === 'exactly-1' ? 'exactly one instance' : 'any number of instances'}; on ${a.placement.runtimes.join(', ')}.${a.placement.note ? ` ${a.placement.note}` : ''}`);
    out.push(`- **Keys:** ${a.keys.length ? a.keys.map(keyText).join('. ') : 'none'}.`);
    out.push(`- **Ports:** ${list(ports)}.${drivers.length ? ` On local: ${drivers.join(', ')}.` : ''}`);
    out.push(`- **Calls:** ${list(exCalls(a).map(code))}.`);
    out.push(`- **Decisions:** ${list(a.adrs.map(adrLink))}.`);
    out.push(`- **Requirement areas:** ${list(a.requirement_areas.map((c) => `[${c}](/requirements/${c.toLowerCase()}/)`))}.`);
    out.push(`- **Standards:** ${list(a.standards.map((s) => `${s} ${standards.get(s)?.name ?? ''}`.trim()), 'none', '; ')}.`);
    out.push(`- **Issues:** ${list(a.issues.map(issueLink))}; label ${code(a.label)}.`);
  }
  out.push('', END);
  return out.join('\n');
}
if (existsSync(join(root, PAGE))) {
  const page = read(PAGE);
  const b = page.indexOf(BEGIN);
  const e = page.indexOf(END);
  if (b < 0 || e < b) error(`${PAGE}: the generated block markers are missing`);
  else {
    const want = render();
    const have = page.slice(b, e + END.length);
    if (have !== want) {
      if (write) {
        writeFileSync(join(root, PAGE), page.slice(0, b) + want + page.slice(e + END.length));
        console.log(`check-actors: rewrote the generated block of ${PAGE}`);
      } else error(`${PAGE}: the generated block is stale; run \`just actors-write\``);
    }
  }
} else error(`${PAGE} is missing`);

console.log(`check-actors: ${annotated} requirement records name actors`);
finish(actors.length, 'actors');
